    private void btn_eliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_eliminarActionPerformed
        if (tbl_clientes.getRowCount()>0) {
            if (tbl_clientes.getSelectedRow() != -1) {
                int idCliente = Integer.parseInt(tbl_clientes.getValueAt(tbl_clientes.getSelectedRow(),0).toString());
                int res = JOptionPane.showConfirmDialog(null, "Estas seguro de eliminar este cliente?");
                if (JOptionPane.OK_OPTION == res) {
                    cl.setIdCliente(idCliente);
                    CDao.eliminar(cl);
                    JOptionPane.showMessageDialog(null, "Cliente Eliminado :(",
                            "INFORMATION",JOptionPane.INFORMATION_MESSAGE);
                    CargarClientes();
                }else{
                     JOptionPane.showMessageDialog(null, "Operacion Cancelada",
                            "INFORMATION",JOptionPane.INFORMATION_MESSAGE);
                }
            }
        }
    }//GEN-LAST:event_btn_eliminarActionPerformed

