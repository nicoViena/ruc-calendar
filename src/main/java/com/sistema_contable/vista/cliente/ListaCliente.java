    public void CargarClientes(){
        List<Cliente> lista = CDao.listar();
        DefaultTableModel table = (DefaultTableModel) tbl_clientes.getModel();
        table.setNumRows(0);
        for (Cliente c : lista) {
            Object[] rowData = {
                c.getIdCliente(),
                c.getRUC(),
                c.getNombre()
            };
            table.addRow(rowData);
        }
        tbl_clientes.setModel(table);
    }

